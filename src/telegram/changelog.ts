export function formatChangelog(): string {
  if (CHANGELOG.length === 0) return '📝 Поки що немає записів про оновлення.';

  return CHANGELOG.map(
    (e) => `📅 ${e.date} — ${e.title}\n\n${e.items.map((i) => `• ${i}`).join('\n')}`,
  ).join('\n\n━━━━━━━━━━━━━━━\n\n');
}

